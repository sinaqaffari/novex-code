import { expect, test } from '@playwright/test';
import { readFile, stat } from 'node:fs/promises';
import path from 'node:path';
import { builderSnapshotClient } from '../../src/lib/backend/builder.ts';
import { getCommerceSnapshot } from '../../src/lib/backend/commerce.ts';

test('a ready-made template is edited, published, shopped and submitted through Go and PostgreSQL', async ({ page }) => {
	test.skip(process.env.NOVEX_E2E_BUILDER_POSTGRES !== 'initialized' || process.env.NOVEX_E2E_COMMERCE_POSTGRES !== 'initialized', 'Requires explicitly disposable Builder and commerce stores.');
	const slug = `fullstack-${Date.now().toString(36)}`;
	await page.goto('/marketplace/shop-landing/preview');
	await page.getByRole('link', { name: 'استفاده از این طرح' }).click();
	await expect(page).toHaveURL(/\/cms\/login\?next=/);
	await page.getByLabel('نام کاربری').fill('novex-e2e-admin');
	await page.locator('#cms-password').fill('novex-e2e-password-only-for-local-tests');
	await page.getByRole('button', { name: 'ورود به پنل' }).click();
	await expect(page).toHaveURL(/\/cms\/pages\/new\?template=shop-landing/);
	await page.getByLabel('عنوان صفحه').fill('فروشگاه آزمایشی PostgreSQL');
	await page.getByLabel('نامک لاتین').fill(slug);
	await page.getByRole('button', { name: 'ساخت و ویرایش' }).click();
	await page.waitForURL((url) => url.pathname === `/cms/builder/${slug}`);
	const canvas = page.getByTestId('builder-canvas');
	await expect(canvas).toContainText('زیبایی در چیزهای روزمره');
	const headline = canvas.getByRole('heading', { name: 'زیبایی در چیزهای روزمره' });
	await headline.dblclick();
	const editable = canvas.getByRole('textbox', { name: 'ویرایش تیتر' });
	await editable.fill('فروشگاه واقعی ما'); await editable.press('Enter');
	await page.getByTestId('save-page').click();
	await expect(page.locator('.builder-save-state--saved')).toBeVisible();
	await page.reload();
	await expect(canvas).toContainText('فروشگاه واقعی ما');
	await page.getByTestId('publish-page').click();
	await expect(page.locator('.builder-message')).toContainText('صفحه منتشر شد');
	const backendBuilder = await builderSnapshotClient.get();
	const storedBuilder = backendBuilder.snapshot as { pages: Record<string, { revision: number; publishedRevision: number }> };
	expect(backendBuilder.revision).toBeGreaterThan(0);
	expect(storedBuilder.pages[slug].publishedRevision).toBeGreaterThan(0);
	await expect(stat(path.join(process.env.NOVEX_E2E_DATA_DIR!, 'builder-pages.json'))).rejects.toMatchObject({ code: 'ENOENT' });
	await page.setViewportSize({ width: 320, height: 844 });
	await page.goto(`/pages/${slug}`);
	await expect(page.locator('.nvx-page__content')).toContainText('فروشگاه واقعی ما');
	await expect(page.locator('.nvx-builder-product-grid')).toContainText('محصول آزمایشی');
	const dimensions = await page.evaluate(() => ({ viewport: document.documentElement.clientWidth, content: document.documentElement.scrollWidth }));
	expect(dimensions.content).toBeLessThanOrEqual(dimensions.viewport + 1);
	const form = page.locator('.nvx-inquiry');
	const name = `بازدیدکنندهٔ فول‌استک ${Date.now()}`;
	await form.getByLabel('نام', { exact: true }).fill(name);
	await form.getByLabel('ایمیل یا شمارهٔ تماس').fill('fullstack@example.invalid');
	await form.getByLabel('پیام', { exact: true }).fill('درخواست آزمایشی از قالب فروشگاهی');
	await form.getByRole('button', { name: 'ارسال درخواست' }).click();
	await expect(form.getByRole('status')).toContainText('درخواست شما ثبت شد');
	await page.goto('/cms/inquiries');
	const item = page.locator('.inquiry-card').filter({ hasText: name });
	await expect(item).toContainText('fullstack@example.invalid');
	await item.getByText('حذف دائمی', { exact: true }).click();
	await item.getByLabel('حذف دائمی این درخواست را تأیید می‌کنم.').check();
	await item.getByRole('button', { name: 'حذف درخواست' }).click();
	await expect(page.locator('.inquiry-card').filter({ hasText: name })).toHaveCount(0);
	await page.goto(`/pages/${slug}`);
	await page.getByRole('link', { name: 'مشاهدهٔ محصول آزمایشی' }).click();
	await page.getByRole('button', { name: 'افزودن به سبد خرید' }).click();
	await page.goto('/shop/cart');
	await page.getByRole('link', { name: 'ادامهٔ فرآیند خرید' }).click();
	const idempotencyKey = await page.locator('input[name="idempotencyKey"]').inputValue();
	const checkoutItems = await page.locator('input[name="checkoutItems"]').inputValue();
	const customer = { customerName: 'خریدار فول‌استک', email: '', phone: '09123456789', city: 'تهران', address: 'نشانی آزمایشی', note: '', discountCode: '' };
	await page.locator('#customerName').fill(customer.customerName);
	await page.locator('#phone').fill(customer.phone); await page.locator('#city').fill(customer.city); await page.locator('#address').fill(customer.address);
	await page.getByRole('button', { name: 'ثبت سفارش' }).click();
	await page.waitForURL((url) => /^\/shop\/order\/NVX-\d+$/.test(url.pathname));
	const number = new URL(page.url()).pathname.split('/').at(-1);
	const replay = await page.request.post('/shop/api/checkout', { headers: { accept: 'application/json' }, multipart: { ...customer, idempotencyKey, checkoutItems } });
	expect(replay.status()).toBe(200); expect((await replay.json()).number).toBe(number);
	const commerce = (await getCommerceSnapshot()).snapshot as { products: Array<{ id: string; stock: number }>; orders: Array<{ number: string }> };
	expect(commerce.products.find((item) => item.id === 'e2e_product_internal_id')?.stock).toBe(1);
	expect(commerce.orders).toHaveLength(1); expect(commerce.orders[0].number).toBe(number);
	const original = JSON.parse(await readFile(path.join(process.env.NOVEX_E2E_DATA_DIR!, 'commerce.json'), 'utf8')) as { orders: unknown[] };
	expect(original.orders).toHaveLength(0);
	await page.goto('/cms/orders'); await expect(page.locator('main')).toContainText(customer.customerName);
	await page.goto('/cms/settings'); await expect(page.locator('[data-builder-storage]')).toContainText('PostgreSQL');
});
