import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { cp, mkdir, mkdtemp, readFile, rm, stat, symlink, unlink, writeFile } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { it } from 'node:test';

it('creates private stable Docker secrets once and never removes data volumes', async () => {
	const root = await mkdtemp(path.join(os.tmpdir(), 'novex-compose-unit-'));
	try {
		await mkdir(path.join(root, 'scripts'));
		await mkdir(path.join(root, 'bin'));
		await mkdir(path.join(root, 'data'));
		await cp('scripts/fullstack-compose.mjs', path.join(root, 'scripts/fullstack-compose.mjs'));
		await writeFile(path.join(root, 'data', 'commerce.json'), 'user-data-must-remain');
		const fakeDocker = path.join(root, 'bin', 'docker');
		await writeFile(fakeDocker, '#!/bin/sh\n[ ${#POSTGRES_PASSWORD} -ge 32 ] && [ ${#NOVEX_BACKEND_TOKEN} -ge 32 ] || exit 4\nprintf "%s\\n" "$*" >> "$FAKE_DOCKER_LOG"\ncase "$*" in *" ps "*) [ "${FAKE_APP_RUNNING:-0}" = 1 ] && printf "app\\n" ;; esac\nexit 0\n', { mode: 0o700 });
		await writeFile(path.join(root, 'bin', 'npm'), '#!/bin/sh\n[ -z "${POSTGRES_PASSWORD:-}" ] && [ ${#NOVEX_BACKEND_TOKEN} -ge 32 ] || exit 6\nprintf "%s %s\\n" "$NOVEX_BACKEND_URL" "$*" > "$FAKE_NPM_LOG"\n', { mode: 0o700 });
		const env: NodeJS.ProcessEnv = { ...process.env, PATH: `${path.join(root, 'bin')}${path.delimiter}${process.env.PATH}`, FAKE_DOCKER_LOG: path.join(root, 'docker.log'), FAKE_NPM_LOG: path.join(root, 'npm.log'), NOVEX_DEV_HOST: '127.0.0.1' };
		delete env.POSTGRES_PASSWORD; delete env.NOVEX_BACKEND_TOKEN;
		const run = (action: string, ...args: string[]) => spawnSync(process.execPath, [path.join(root, 'scripts/fullstack-compose.mjs'), action, ...args], { cwd: root, env, encoding: 'utf8' });
		assert.equal(run('up').status, 0);
		const passwordPath = path.join(root, '.novex-secrets', 'postgres-password');
		const tokenPath = path.join(root, '.novex-secrets', 'backend-token');
		const password = await readFile(passwordPath, 'utf8'), token = await readFile(tokenPath, 'utf8');
		assert.match(password.trim(), /^[a-f0-9]{64}$/); assert.match(token.trim(), /^[a-f0-9]{64}$/);
		assert.equal((await stat(passwordPath)).mode & 0o077, 0);
		assert.equal((await stat(tokenPath)).mode & 0o077, 0);
		assert.equal(run('up').status, 0);
		assert.equal(await readFile(passwordPath, 'utf8'), password); assert.equal(await readFile(tokenPath, 'utf8'), token);
		assert.equal(run('dev').status, 0);
		assert.match(await readFile(path.join(root, 'npm.log'), 'utf8'), /http:\/\/127\.0\.0\.1:8081 run dev -- --host 127\.0\.0\.1/);
		const beforeRejectedCommands = await readFile(path.join(root, 'docker.log'), 'utf8');
		assert.notEqual(run('migrate-commerce').status, 0, 'offline migration needs explicit confirmation');
		assert.notEqual(run('export-commerce').status, 0, 'export requires an explicit new path');
		assert.notEqual(run('migrate-builder').status, 0, 'builder migration needs explicit confirmation');
		assert.notEqual(run('export-builder').status, 0, 'builder export requires an explicit new path');
		assert.equal(await readFile(path.join(root, 'docker.log'), 'utf8'), beforeRejectedCommands);
		env.FAKE_APP_RUNNING = '1';
		const active = run('docker-migrate-commerce', '--confirm-offline');
		assert.notEqual(active.status, 0); assert.match(active.stderr, /Stop the Docker app/);
		env.FAKE_APP_RUNNING = '0';
		assert.equal(run('docker-migrate-commerce', '--confirm-offline').status, 0);
		assert.equal(run('docker-migrate-builder', '--confirm-offline').status, 0);
		assert.equal(run('docker-export-builder', '--output', '/app/data/builder-backup.json').status, 0);
		assert.notEqual(run('docker-export-builder', '--output', '/app/data/../unsafe.json').status, 0);
		assert.notEqual(run('docker-export-commerce', '--output', '/app/data/../unsafe.json').status, 0);
		assert.equal(run('docker-export-commerce', '--output', '/app/data/commerce-backup.json').status, 0);
		assert.equal(run('down').status, 0);
		const log = await readFile(path.join(root, 'docker.log'), 'utf8');
		assert.match(log, / up --build -d/); assert.match(log, /docker-compose\.local-backend\.yml up --build -d backend/); assert.match(log, /run --rm --no-deps --build --entrypoint node.*scripts\/migrate-commerce\.ts --confirm-offline/); assert.match(log, /scripts\/export-commerce\.ts --output \/app\/data\/commerce-backup\.json/); assert.match(log, / down/);
		assert.match(log, /BUILDER_DATA_FILE=\/app\/data\/builder-pages\.json.*scripts\/migrate-builder\.ts --confirm-offline/);
		assert.match(log, /NOVEX_BUILDER_STORE=postgres.*scripts\/export-builder\.ts --output \/app\/data\/builder-backup\.json/);
		assert.doesNotMatch(log, /--volumes| -v(?:\s|$)/);
		assert.equal(await readFile(path.join(root, 'data', 'commerce.json'), 'utf8'), 'user-data-must-remain');
		await unlink(tokenPath);
		const partial = run('up'); assert.notEqual(partial.status, 0);
		assert.match(partial.stderr, /missing/i);
		await assert.rejects(stat(tokenPath));
		await symlink(passwordPath, tokenPath);
		assert.notEqual(run('up').status, 0, 'a symlink must not be followed as a secret');
	} finally { await rm(root, { recursive: true, force: true }); }
});
